import path from 'node:path';
import {startExtension} from '../harness.mjs';
const ROOT = path.resolve(decodeURIComponent(new URL('../..', import.meta.url).pathname.replace(/^\/(\w:)/, '$1')));
const {browser, id, stop} = await startExtension(path.join(ROOT, 'extension'));
const pop = await browser.newPage();
await pop.goto(`chrome-extension://${id}/popup.html`, {waitUntil:'load'});
await new Promise(r=>setTimeout(r,500));
const off = await pop.evaluate(() => new Promise(res => {
  document.querySelector('.tile[data-id="pixel"]').click();
  setTimeout(() => chrome.storage.local.get('features', s => res(s.features)), 200);
}));
console.log('storage after off', JSON.stringify(off));
const tab = await browser.newPage();
await tab.setViewport({width: 1440, height: 900});
await tab.goto('https://turbowarp.org/editor', {waitUntil:'networkidle2', timeout:120000});
await new Promise(r=>setTimeout(r,5000));
await tab.keyboard.press('Escape');
await tab.evaluate(() => document.querySelectorAll('[role="tab"]')[1].click());
await new Promise(r=>setTimeout(r,3000));
const tools = await tab.evaluate(() => ({tools:[...document.querySelectorAll('.adox-tool')].map(b=>b.dataset.adoxKey), px: !!document.querySelector('.adox-px-btn')}));
console.log('with pixel off', JSON.stringify(tools));
await pop.reload({waitUntil:'load'});
await new Promise(r=>setTimeout(r,400));
await pop.evaluate(() => document.querySelector('.tile[data-id="pixel"]').click());
await new Promise(r=>setTimeout(r,700));
await tab.reload({waitUntil:'networkidle2'});
await new Promise(r=>setTimeout(r,5000));
await tab.keyboard.press('Escape');
await tab.evaluate(() => document.querySelectorAll('[role="tab"]')[1].click());
await new Promise(r=>setTimeout(r,3000));
const tools2 = await tab.evaluate(() => ({tools:[...document.querySelectorAll('.adox-tool')].map(b=>b.dataset.adoxKey), px: !!document.querySelector('.adox-px-btn')}));
console.log('with pixel on', JSON.stringify(tools2));
stop();
